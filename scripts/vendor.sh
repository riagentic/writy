#!/bin/sh
# Bundle the editor libraries into src/vendor/pm.js (+ pm.d.ts types).
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
W=$(mktemp -d)
PKGS="prosemirror-model@1.25.12 prosemirror-state@1.4.4 prosemirror-view@1.42.6 prosemirror-transform@1.12.2 prosemirror-commands@1.7.2 prosemirror-keymap@1.2.3 prosemirror-history@1.5.1 prosemirror-inputrules@1.5.1 prosemirror-schema-list@1.5.1 prosemirror-tables@1.8.5 prosemirror-dropcursor@1.8.4 prosemirror-gapcursor@1.4.1 @codemirror/state@6.7.6 @codemirror/view@6.43.13 @codemirror/commands@6.11.1 @codemirror/language@6.12.4 @codemirror/search@6.7.2 @lezer/highlight@1.2.5"
cd "$W" && npm init -y >/dev/null && npm i --no-audit --no-fund $PKGS esbuild@0.25.12 >/dev/null
cp "$ROOT/scripts/vendor-entry.ts" "$W/entry.ts"
{ echo '// @ts-self-types="./pm.d.ts"'; npx esbuild entry.ts --bundle --format=esm --minify --legal-comments=none; } > "$ROOT/src/vendor/pm.js"
{ echo "// Types for pm.js — generated by scripts/vendor.sh"; for p in $PKGS; do n=${p%@*}; v=${p##*@}; a=$(grep "\"$n\"" "$ROOT/scripts/vendor-entry.ts" | sed 's/export \* as \([a-zA-Z]*\).*/\1/'); echo "export * as $a from \"npm:$n@$v\";"; done; } > "$ROOT/src/vendor/pm.d.ts"
rm -rf "$W"
echo "pm.js $(wc -c < "$ROOT/src/vendor/pm.js") bytes"
